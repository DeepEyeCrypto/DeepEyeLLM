/**
 * Returns a responsive typography scale scaled dynamically based on screen width class.
 */
@Composable
fun responsiveTypography(isExpandedScreen: Boolean = false): Typography {
    return if (isExpandedScreen) {
        Typography.copy(
            headlineLarge = Typography.headlineLarge.copy(fontSize = 26.sp, lineHeight = 32.sp),
            headlineMedium = Typography.headlineMedium.copy(fontSize = 20.sp, lineHeight = 26.sp),
            titleLarge = Typography.titleLarge.copy(fontSize = 18.sp, lineHeight = 24.sp),
            bodyLarge = Typography.bodyLarge.copy(fontSize = 15.sp, lineHeight = 22.sp),
            bodyMedium = Typography.bodyMedium.copy(fontSize = 14.sp, lineHeight = 20.sp)
        )
    } else {
        Typography
    }
}
